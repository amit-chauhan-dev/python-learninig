# opening a file - open()

file = open("filename.txt", "mode")

# Common Mode
# Mode,   Meaning,          Description
#  r,     Read (default),   Opens file for reading
#  w,     Write,            Creates new file or overwrites existing file
#  a,     Append,           Adds data at the end of the file
#  x,     Create,           "Creates file, error if already exists"
#  rb,    Read Binary,      "For images, PDFs, etc."
#  wb,    Write Binary,     For writing binary data