# Strings (Text)

name = "Python Programing"

# Slicing
print(name[0])  # P
print(name[0:6])    # Python
print(name[-1])     # g (last character)
print(name[::-1])   # reverse string 

# Common Method
print(name.upper())
print(name.lower())
print(name.replace("Python", "Java"))
print(name.split())
print(len(name))

